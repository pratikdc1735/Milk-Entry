@Composable
fun BillStatusBadge(status: String) {
    val (bg, fg, label) = when (status.uppercase()) {
        "PAID" -> Triple(DairyFreshGreenLight, DairyFreshGreen, "PAID")
        "PARTIAL" -> Triple(StatusAmberContainer, StatusAmber, "PARTIAL")
        else -> Triple(StatusErrorContainer, StatusError, "UNPAID")
    }
    StatusPillBadge(text = label, containerColor = bg, contentColor = fg)
}

